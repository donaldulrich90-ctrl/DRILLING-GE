    function normalizeLocale(loc) {
        var s = String(loc || 'fr').toLowerCase().slice(0, 2);
        return s === 'en' ? 'en' : 'fr';
    }

    var locale = normalizeLocale(
        typeof localStorage !== 'undefined' ? localStorage.getItem(STORAGE_KEY) : 'fr'
    );

    function t(key) {
        var k = String(key || '');
        var table = DICT[locale] || DICT.fr;
        if (Object.prototype.hasOwnProperty.call(table, k)) return table[k];
        if (locale !== 'fr' && DICT.fr && Object.prototype.hasOwnProperty.call(DICT.fr, k)) return DICT.fr[k];
        return k;
    }

    function getLocale() {
        return locale;
    }

    function setLocale(loc, onApplied) {
        locale = normalizeLocale(loc);
        try {
            localStorage.setItem(STORAGE_KEY, locale);
        } catch (e) {}
        if (typeof onApplied === 'function') onApplied();
    }

    function applyDom(root) {
        root = root || (typeof document !== 'undefined' ? document : null);
        if (!root || !root.querySelectorAll) return;

        root.querySelectorAll('[data-i18n]').forEach(function (el) {
            var k = el.getAttribute('data-i18n');
            if (k) el.textContent = t(k);
        });
        root.querySelectorAll('[data-i18n-html]').forEach(function (el) {
            var k = el.getAttribute('data-i18n-html');
            if (k) el.innerHTML = t(k);
        });
        root.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
            var k = el.getAttribute('data-i18n-placeholder');
            if (k) el.setAttribute('placeholder', t(k));
        });
        root.querySelectorAll('[data-i18n-title]').forEach(function (el) {
            var k = el.getAttribute('data-i18n-title');
            if (k) el.setAttribute('title', t(k));
        });
    }

    window.ForageI18n = {
        t: t,
        getLocale: getLocale,
        setLocale: setLocale,
        applyDom: applyDom,
        _dict: DICT
    };
